# MiniMax compute multiplier (points/credits multiplier shown in UI)
H3_MP_VALUES = {
    "360p": 0.2,
    "480p": 0.4,
    "540p": 0.5,
    "640p": 0.7,
    "720p": 0.9,
    "1080p": 2.0,
    "1K": 1.0,
    "2K": 1.5,
    "4K": 2.5,
    "6K": 4.0
}


def round_to_multiple(val: float, multiple: int = 16) -> int:
    return int(round(val / multiple) * multiple)


class YtonResolutionSelector:
    """
    Standard resolution and aspect ratio selector for Normal and MiniMax H3.
    """
    
    @classmethod
    def INPUT_TYPES(cls) -> Dict[str, Any]:
        return {
            "required": {
                "mode": (["MiniMax H3 (Video)", "Normal (Standard Image/Video)"], {"default": "MiniMax H3 (Video)"}),
                "aspect_ratio": (["16:9", "9:16", "1:1", "4:3", "3:4", "3:2", "2:3", "21:9"], {"default": "16:9"}),
                "resolution": (["360p", "480p", "540p", "640p", "720p", "1080p", "1K", "2K", "4K", "6K"], {"default": "1080p"}),
            },
            "optional": {
                "custom_width": ("INT", {"default": 0, "min": 0, "max": 8192, "step": 8}),
                "custom_height": ("INT", {"default": 0, "min": 0, "max": 8192, "step": 8}),
            }
        }

    RETURN_TYPES = ("INT", "INT", "STRING", "INT", "INT", "FLOAT", "STRING")
    RETURN_NAMES = ("width", "height", "aspect_ratio", "max_side", "min_side", "h3_mp", "resolution_str")
    FUNCTION = "get_resolution"
    CATEGORY = "yton-nodes/Resolution"

    def get_resolution(
        self,
        mode: str,
        aspect_ratio: str,
        resolution: str,
        custom_width: int = 0,
        custom_height: int = 0
    ) -> Tuple[int, int, str, int, int, float, str]:
        # Handle custom override if user provided valid dimensions
        if custom_width > 0 and custom_height > 0:
            w, h = custom_width, custom_height
            if "H3" in mode:
                w = round_to_multiple(w, 16)
                h = round_to_multiple(h, 16)
            max_side = max(w, h)
            min_side = min(w, h)
            h3_mp = H3_MP_VALUES.get(resolution, 1.0)
            return (w, h, aspect_ratio, max_side, min_side, h3_mp, "custom")

        # Preset lookup
        preset_map = H3_RATIO_PRESETS if "H3" in mode else NORMAL_RATIO_PRESETS
        dims = preset_map.get((aspect_ratio, resolution))

        if dims is None:
            # Fallback calculation if combination is not explicit
            ratio_parts = [float(x) for x in aspect_ratio.split(":")]
            target_ratio = ratio_parts[0] / ratio_parts[1]
            short_side = 1088 if ("H3" in mode and resolution == "1080p") else 1080
            
            if target_ratio >= 1.0:
                h = short_side
                w = int(h * target_ratio)
            else:
                w = short_side
                h = int(w / target_ratio)
                
            if "H3" in mode:
                w = round_to_multiple(w, 16)
                h = round_to_multiple(h, 16)
        else:
            w, h = dims

        max_side = max(w, h)
        min_side = min(w, h)
        h3_mp = float(H3_MP_VALUES.get(resolution, 1.0))

        return (int(w), int(h), aspect_ratio, int(max_side), int(min_side), h3_mp, resolution)
